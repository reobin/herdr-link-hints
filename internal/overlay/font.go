// glyph returns the bitmap for r. Codes are drawn lowercase whatever the
// alphabet's case.
func glyph(r rune) ([glyphHeight]byte, bool) {
	if r >= 'A' && r <= 'Z' {
		r += 'a' - 'A'
	}
	bitmap, ok := glyphs[r]
	return bitmap, ok
}
