func wide(r rune) bool {
	lo, hi := 0, len(wideRanges)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < wideRanges[mid].lo:
			hi = mid - 1
		case r > wideRanges[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}
